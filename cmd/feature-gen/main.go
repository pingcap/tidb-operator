package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/spf13/pflag"
	"k8s.io/gengo/v2"
	"k8s.io/gengo/v2/generator"
	"k8s.io/gengo/v2/namer"
	"k8s.io/gengo/v2/types"
)

const runtimePackageName = "features"

const metaPackage = "github.com/pingcap/tidb-operator/api/v2/meta/v1alpha1"
const metaImport = `meta "github.com/pingcap/tidb-operator/api/v2/meta/v1alpha1"`

type args struct {
	root         string
	outputDir    string
	goHeaderFile string
	check        bool
}

func main() {
	a := args{}
	pflag.StringVar(&a.root, "root", ".", "repository root")
	pflag.StringVar(&a.outputDir, "output-dir", "", "runtime features output directory (defaults to <root>/pkg/features)")
	pflag.StringVar(&a.goHeaderFile, "go-header-file", "", "boilerplate header file; YEAR is replaced with the current year")
	pflag.BoolVar(&a.check, "check", false, "check generated files without writing")
	pflag.CommandLine.AddGoFlagSet(flag.CommandLine)
	pflag.Parse()
	if err := execute(a, pflag.Args()); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func execute(a args, inputs []string) (resultErr error) {
	if a.goHeaderFile == "" {
		return fmt.Errorf("--go-header-file must be specified")
	}
	if len(inputs) != 1 {
		return fmt.Errorf("exactly one feature API package must be specified")
	}
	header, err := gengo.GoBoilerplate(a.goHeaderFile, gengo.StdBuildTag, "// Code generated by feature-gen. DO NOT EDIT.")
	if err != nil {
		return err
	}
	// API declarations must remain visible to other generators, which load
	// packages with ignore_autogenerated enabled (for example deepcopy-gen).
	apiHeader, err := gengo.GoBoilerplate(a.goHeaderFile, "", "// Code generated by feature-gen. DO NOT EDIT.")
	if err != nil {
		return err
	}
	// Validate all histories before gengo can write any target.
	outputs, err := prepare(a.root)
	if err != nil {
		return err
	}
	var temporary string
	if a.check {
		temporary, err = os.MkdirTemp("", "feature-gen-")
		if err != nil {
			return err
		}
		defer func() { resultErr = errors.Join(resultErr, os.RemoveAll(temporary)) }()
	}
	var targetErr error
	targets := func(c *generator.Context) []generator.Target {
		if len(c.Inputs) != 1 {
			targetErr = fmt.Errorf("expected one loaded feature API package, got %d", len(c.Inputs))
			return nil
		}
		pkg := c.Universe[c.Inputs[0]]
		sourceDir, err := filepath.Abs(filepath.Join(a.root, filepath.Dir(sourcePath)))
		if err != nil {
			targetErr = err
			return nil
		}
		if filepath.Clean(pkg.Dir) != sourceDir {
			targetErr = fmt.Errorf("input package must contain %s", sourcePath)
			return nil
		}
		result := make([]generator.Target, 0, len(outputs))
		for _, out := range outputs {
			targetHeader := apiHeader
			dir := filepath.Join(a.root, filepath.Dir(out.Path))
			pkgPath := metaPackage
			if out.Package == runtimePackageName {
				targetHeader = header
				pkgPath = "github.com/pingcap/tidb-operator/v2/pkg/features"
				if a.outputDir != "" {
					dir = a.outputDir
				}
			}
			if a.check {
				dir = filepath.Join(temporary, filepath.Dir(out.Path))
			}
			result = append(result, &generator.SimpleTarget{
				PkgName: out.Package, PkgPath: pkgPath, PkgDir: dir, HeaderComment: targetHeader,
				// Snapshots are generated once in Init, not once per input type.
				FilterFunc: func(*generator.Context, *types.Type) bool { return false },
				GeneratorsFunc: func(*generator.Context) []generator.Generator {
					return []generator.Generator{&featureGenerator{
						GoGenerator: generator.GoGenerator{OutputFilename: filepath.Base(out.Path), OptionalBody: out.Data},
						imports:     out.Imports,
					}}
				},
			})
		}
		return result
	}
	if err := gengo.Execute(namer.NameSystems{"raw": namer.NewRawNamer("", nil)}, "raw", targets, gengo.StdBuildTag, inputs); err != nil {
		return err
	}
	if targetErr != nil {
		return targetErr
	}
	if a.check {
		return checkOutputs(a, temporary, outputs)
	}
	return nil
}

func checkOutputs(a args, temporary string, outputs []output) error {
	for _, out := range outputs {
		path := filepath.Join(a.root, out.Path)
		if out.Package == runtimePackageName && a.outputDir != "" {
			path = filepath.Join(a.outputDir, filepath.Base(out.Path))
		}
		actual, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		expected, err := os.ReadFile(filepath.Join(temporary, out.Path))
		if err != nil {
			return err
		}
		if !bytes.Equal(actual, expected) {
			return fmt.Errorf("%s is stale; run make featuregen", path)
		}
	}
	return nil
}

type featureGenerator struct {
	generator.GoGenerator
	imports []string
}

func (g *featureGenerator) Imports(*generator.Context) []string { return g.imports }
